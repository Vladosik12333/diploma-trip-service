CREATE TABLE trips
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT                   NOT NULL,
    title         VARCHAR(255)             NOT NULL,
    start_date    DATE                     NOT NULL,
    end_date      DATE                     NOT NULL,
    budget_amount NUMERIC(12, 2)           NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE categories
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64) UNIQUE       NOT NULL,
    name        VARCHAR(120)             NOT NULL,
    description TEXT                     NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);


CREATE TABLE trip_locations
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id         BIGINT UNIQUE            NOT NULL,
    google_place_id VARCHAR(255)             NOT NULL,
    city            VARCHAR(255)             NOT NULL,
    country         VARCHAR(255)             NOT NULL,
    latitude        NUMERIC(9, 6)            NOT NULL,
    longitude       NUMERIC(9, 6)            NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_trip_locations_trip FOREIGN KEY (trip_id)
        REFERENCES trips (id) ON DELETE CASCADE
);


CREATE TABLE trip_categories
(
    trip_id     BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    CONSTRAINT pk_trip_categories PRIMARY KEY (trip_id, category_id),
    CONSTRAINT fk_trip_categories_trip FOREIGN KEY (trip_id)
        REFERENCES trips (id) ON DELETE CASCADE,
    CONSTRAINT fk_trip_categories_category FOREIGN KEY (category_id)
        REFERENCES categories (id)
);
