TRUNCATE TABLE trips CASCADE;

DROP TABLE trip_locations;

CREATE TABLE locations
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    geoname_id BIGINT UNIQUE            NOT NULL,
    city       VARCHAR(255)             NOT NULL,
    country    VARCHAR(255)             NOT NULL,
    latitude   NUMERIC(9, 6)            NOT NULL,
    longitude  NUMERIC(9, 6)            NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);


ALTER TABLE trips
    ADD COLUMN location_id     BIGINT      NOT NULL,
    ADD COLUMN currency        CHAR(3)     NOT NULL,
    ADD COLUMN travel_mode     VARCHAR(20) NOT NULL,
    ADD COLUMN travelers_count INT         NOT NULL,
    ADD CONSTRAINT fk_trips_location FOREIGN KEY (location_id) REFERENCES locations (id);

CREATE INDEX ix_trips_user ON trips (user_id, start_date);
CREATE INDEX ix_trips_location ON trips (location_id);
CREATE INDEX ix_trip_categories_category ON trip_categories (category_id);
